// Convert the checked-in Unicode BDF originals to synchronous browser data.
// Run from the repository root: node tools/generate_fonts.js
import { readFileSync, writeFileSync } from 'node:fs';

const specs = [
  ['6x13', 'Fixed 6×13'],
  ['7x14B', 'Fixed Bold 7×14'],
  ['10x20', 'Fixed 10×20'],
  ['ter-u16n', 'Terminus 8×16', 'SIL Open Font License 1.1'],
];

function convert(id, name, license = 'Public domain') {
  const text = readFileSync(`web/fonts/${id}.bdf`, 'utf8');
  const box = /^FONTBOUNDINGBOX (\d+) (\d+) (-?\d+) (-?\d+)$/m.exec(text);
  if (!box) throw new Error(`${id}: missing font bounding box`);
  const [width, height, originX, originY] = box.slice(1).map(Number);
  const glyphs = Object.create(null);
  for (const match of text.matchAll(/^STARTCHAR .*?\n([\s\S]*?)^ENDCHAR$/gm)) {
    const block = match[1];
    const encoding = /^ENCODING (-?\d+)/m.exec(block);
    const bounds = /^BBX (\d+) (\d+) (-?\d+) (-?\d+)$/m.exec(block);
    const bitmap = /^BITMAP\n([\s\S]*)$/m.exec(block);
    if (!encoding || !bounds || !bitmap) throw new Error(`${id}: malformed glyph`);
    const code = Number(encoding[1]);
    if (code < 32 || code > 0x10ffff || (code >= 0xd800 && code <= 0xdfff)) continue;
    const [w, h, x, y] = bounds.slice(1).map(Number);
    const left = x - originX;
    const top = height + originY - h - y;
    if (left < 0 || top < 0 || left + w > width || top + h > height)
      throw new Error(`${id}: glyph ${code} exceeds fixed cell`);
    const rows = Array.from({ length: height }, () => Array(width).fill('0'));
    const sourceRows = bitmap[1].trim().split('\n');
    if (h && sourceRows.length !== h) throw new Error(`${id}: incorrect bitmap height for ${code}`);
    for (let row = 0; row < h; row++) {
      const bytes = sourceRows[row].trim();
      for (let col = 0; col < w; col++) {
        const nibble = Number.parseInt(bytes[Math.floor(col / 4)], 16);
        if (!Number.isFinite(nibble)) throw new Error(`${id}: invalid bitmap for ${code}`);
        if (nibble & (8 >> (col % 4))) rows[top + row][left + col] = '1';
      }
    }
    glyphs[String.fromCodePoint(code)] = rows.map(row => row.join(''));
  }
  return { id, name, width, height, license, glyphs };
}

const fonts = specs.map(spec => convert(...spec));
writeFileSync('web/fonts.js', `// Generated by tools/generate_fonts.js from the BDF files in web/fonts/.\nexport const FONTS = ${JSON.stringify(fonts)};\n`);
