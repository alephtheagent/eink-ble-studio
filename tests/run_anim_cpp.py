#!/usr/bin/env python3
"""Run the animation firmware host tests (storage, wire endpoint, player, codec).

The C++ vector header is generated by tests/anim_vectors.py, which tests/run_cpp.py
also uses, so the same vectors reach every C++ test.

The JSON is the same artifact the JavaScript codec tests consume, so a firmware/site
disagreement fails here. Requires firmware/include/anim_codec.h (the frozen contract
header); the run stops with a clear message if either deliverable is missing.
"""
import os
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
SCRATCH = Path.home() / '.hermes/cache/scratch/eink-studio-host-tests'
SCRATCH.mkdir(parents=True, exist_ok=True)
VECTORS = ROOT / 'tests/vectors-animation.json'
CODEC = ROOT / 'firmware/include/anim_codec.h'

if not CODEC.is_file():
    sys.exit('firmware/include/anim_codec.h is missing (animation contract header)')
if not VECTORS.is_file():
    sys.exit('tests/vectors-animation.json is missing (animation contract vectors)')

from anim_vectors import write_header

write_header(SCRATCH / 'vectors_animation.h')

command = ['g++', '-std=c++11', '-Wall', '-Wextra', '-Werror', '-Wno-misleading-indentation',
           '-fsanitize=address,undefined', '-fno-omit-frame-pointer', '-no-pie', '-g',
           '-I' + str(ROOT / 'firmware/include'), '-I' + str(SCRATCH),
           str(ROOT / 'tests/anim_firmware.cpp'), '-o', str(SCRATCH / 'anim-firmware-tests')]
subprocess.run(command, check=True)
subprocess.run([str(SCRATCH / 'anim-firmware-tests')], check=True,
               env={**os.environ, 'ASAN_OPTIONS': 'detect_leaks=0'})
