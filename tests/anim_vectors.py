#!/usr/bin/env python3
"""Write the C++ animation vector header from tests/vectors-animation.json.

This is the single authoritative generator for `vectors_animation.h`, the schema
tests/anim_firmware.cpp includes (CrcVector/CRC_VECTORS, FrameVector/FRAME_VECTORS,
BlobVector/BLOB_VECTORS, AnimVector/ANIM_VECTORS, PackVector/PACK_VECTORS and
DECODE_VECTORS, RejectVector/REJECT_VECTORS, each with its _COUNT constant).
tests/run_cpp.py calls write_header(); tests/run_anim_cpp.py imports it too, so the
header is never produced by two different implementations.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCRATCH = Path.home() / '.hermes/cache/scratch/eink-studio-host-tests'
VECTORS = ROOT / 'tests/vectors-animation.json'


def write_header(destination=None):
    """Render tests/vectors-animation.json into vectors_animation.h.

    Returns the path written. Raises FileNotFoundError if the vectors are missing.
    """
    target = Path(destination) if destination else SCRATCH / 'vectors_animation.h'
    target.parent.mkdir(parents=True, exist_ok=True)
    data = json.loads(VECTORS.read_text())
    lines = ['// Generated by tests/anim_vectors.py from tests/vectors-animation.json.',
             '#include <stdint.h>',
             '#include <stddef.h>']

    def array(name, values):
        body = ','.join(str(x) for x in values) if values else '0'
        lines.append('static const uint8_t ' + name + '[] = {' + body + '};')

    def count(name, n):
        lines.append('static const size_t %s_COUNT = %d;' % (name, n))

    for i, v in enumerate(data['crc']):
        array('crc_%d' % i, bytes.fromhex(v['hex']))
    lines.append('struct CrcVector {const uint8_t* bytes; size_t size; uint32_t expected;};')
    lines.append('static const CrcVector CRC_VECTORS[] = {' + ','.join(
        '{crc_%d,%d,%du}' % (i, len(bytes.fromhex(v['hex'])), v['value'])
        for i, v in enumerate(data['crc'])) + '};')
    count('CRC_VECTORS', len(data['crc']))

    for i, f in enumerate(data['frames']):
        array('frame_%d' % i, bytes.fromhex(f['hex']))
    lines.append('struct FrameVector {const uint8_t* frame; uint32_t crc;};')
    lines.append('static const FrameVector FRAME_VECTORS[] = {' + ','.join(
        '{frame_%d,%du}' % (i, f['crc']) for i, f in enumerate(data['frames'])) + '};')
    count('FRAME_VECTORS', len(data['frames']))

    for i, b in enumerate(data['blobs']):
        array('blob_%d' % i, bytes.fromhex(b['blobHex']))
    lines.append('struct BlobVector {const uint8_t* blob; size_t size; const uint8_t* prev; '
                 'const uint8_t* decoded; uint8_t kind; uint16_t encLen; uint32_t crc;};')
    lines.append('static const BlobVector BLOB_VECTORS[] = {' + ','.join(
        '{blob_%d,%d,%s,frame_%d,%d,%d,%du}' % (
            i, len(bytes.fromhex(b['blobHex'])),
            'nullptr' if b['prev'] is None else 'frame_%d' % b['prev'],
            b['frame'], b['kind'], b['encLen'], b['crc'])
        for i, b in enumerate(data['blobs'])) + '};')
    count('BLOB_VECTORS', len(data['blobs']))

    for i, a in enumerate(data['animations']):
        lines.append('static const uint16_t anim_%d[] = {%s};' % (
            i, ','.join(str(x) for x in a['frames']) if a['frames'] else '0'))
    lines.append('struct AnimVector {const uint16_t* frames; size_t count; uint32_t crc;};')
    lines.append('static const AnimVector ANIM_VECTORS[] = {' + ','.join(
        '{anim_%d,%d,%du}' % (i, len(a['frames']), a['crc'])
        for i, a in enumerate(data['animations'])) + '};')
    count('ANIM_VECTORS', len(data['animations']))

    for i, p in enumerate(data['packbits']):
        array('raw_%d' % i, bytes.fromhex(p['rawHex']))
        array('packed_%d' % i, bytes.fromhex(p['encodedHex']))
    lines.append('struct PackVector {const uint8_t* raw; size_t rawSize; const uint8_t* packed; size_t packedSize;};')
    lines.append('static const PackVector PACK_VECTORS[] = {' + ','.join(
        '{raw_%d,%d,packed_%d,%d}' % (i, len(bytes.fromhex(p['rawHex'])), i, len(bytes.fromhex(p['encodedHex'])))
        for i, p in enumerate(data['packbits'])) + '};')
    count('PACK_VECTORS', len(data['packbits']))

    for i, p in enumerate(data['packbitsDecode']):
        array('draw_%d' % i, bytes.fromhex(p['rawHex']))
        array('denc_%d' % i, bytes.fromhex(p['encodedHex']))
    lines.append('static const PackVector DECODE_VECTORS[] = {' + ','.join(
        '{draw_%d,%d,denc_%d,%d}' % (i, len(bytes.fromhex(p['rawHex'])), i, len(bytes.fromhex(p['encodedHex'])))
        for i, p in enumerate(data['packbitsDecode'])) + '};')
    count('DECODE_VECTORS', len(data['packbitsDecode']))

    for i, r in enumerate(data['rejects']):
        array('reject_%d' % i, bytes.fromhex(r['blobHex']))
    lines.append('struct RejectVector {const uint8_t* blob; size_t size; uint8_t error; uint8_t headerStage;};')
    lines.append('static const RejectVector REJECT_VECTORS[] = {' + ','.join(
        '{reject_%d,%d,%d,%d}' % (i, len(bytes.fromhex(r['blobHex'])), r['error'],
                                  1 if r['stage'] == 'header' else 0)
        for i, r in enumerate(data['rejects'])) + '};')
    count('REJECT_VECTORS', len(data['rejects']))

    target.write_text('\n'.join(lines) + '\n')
    return target


if __name__ == '__main__':
    print(write_header())
