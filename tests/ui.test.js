import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { JSDOM } from 'jsdom';
import { createCanvas, loadImage } from '@napi-rs/canvas';
const ROOT=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
test('editor surface: approved PNG→native pixels→download, menus, keyboard, pointer, filters and local file',async()=>{
 const dom=new JSDOM(fs.readFileSync(path.join(ROOT,'web/index.html'),'utf8'),{url:'http://localhost/'});
 const {window}=dom,doc=window.document;
 Object.defineProperty(globalThis,'navigator',{value:window.navigator,configurable:true});
 Object.assign(globalThis,{document:doc,Event:window.Event});
 const canvases=new WeakMap();
 window.HTMLCanvasElement.prototype.getContext=function(){
  if(!canvases.has(this))canvases.set(this,createCanvas(this.width,this.height));
  const ctx=canvases.get(this).getContext('2d');
  return new Proxy(ctx,{get(target,key){if(key==='drawImage')return (image,...args)=>target.drawImage(image.native??image,...args);const v=target[key];return typeof v==='function'?v.bind(target):v;}});
 };
 window.HTMLCanvasElement.prototype.toBlob=function(callback){callback(new Blob([canvases.get(this).toBuffer('image/png')],{type:'image/png'}));};
 const objects=new Map();let count=0;const downloads=[];
 globalThis.URL.createObjectURL=blob=>{const key='blob:local-'+(++count);objects.set(key,blob);return key;};
 globalThis.URL.revokeObjectURL=key=>objects.delete(key);
 window.HTMLAnchorElement.prototype.click=function(){downloads.push({name:this.download,blob:objects.get(this.href)});};
 globalThis.Image=class {async decode(){this.native=await loadImage(this.src.startsWith('blob:')?Buffer.from(await objects.get(this.src).arrayBuffer()):path.join(ROOT,'web',this.src));this.naturalWidth=this.native.width;this.naturalHeight=this.native.height;}};
 const $=id=>doc.getElementById(id),tick=()=>new Promise(r=>setImmediate(r));
 await import('../web/app.js');
 assert.equal($('connect').disabled,true);assert.match($('status').textContent,/Web Bluetooth unavailable/);
 $('reference').click();for(let n=0;n<100&&!$('image-name').textContent.includes('Approved');n++)await new Promise(r=>setTimeout(r,5));
 assert.equal($('image-name').textContent,'Approved native reference');
 $('frame').click();const approved=fs.readFileSync(path.join(ROOT,'tests/fixtures/approved-frame.bin'));
 assert.deepEqual(Buffer.from(await downloads.at(-1).blob.arrayBuffer()),approved);
 $('png').click();const saved=await loadImage(Buffer.from(await downloads.at(-1).blob.arrayBuffer()));
 assert.equal(saved.width,122);assert.equal(saved.height,250);
 const raster=createCanvas(122,250);raster.getContext('2d').drawImage(saved,0,0);
 const original=await loadImage(path.join(ROOT,'web/reference.png'));const other=createCanvas(122,250);other.getContext('2d').drawImage(original,0,0);
 assert.deepEqual(raster.getContext('2d').getImageData(0,0,122,250).data,other.getContext('2d').getImageData(0,0,122,250).data);
 $('preview').focus();$('preview').dispatchEvent(new window.KeyboardEvent('keydown',{key:'ArrowRight',shiftKey:true,bubbles:true}));assert.equal($('x').value,'10');
 $('preview').dispatchEvent(new window.KeyboardEvent('keydown',{key:'+',bubbles:true}));assert.equal(Number($('zoom').value),1.1);
 $('preview').setPointerCapture=()=>{};$('preview').getBoundingClientRect=()=>({width:244,height:500});
 function pointer(type,x,y,id=1){const e=new window.Event(type);Object.assign(e,{button:0,pointerId:id,clientX:x,clientY:y});$('preview').dispatchEvent(e);}
 pointer('pointerdown',0,0);pointer('pointermove',20,40);pointer('pointerup',20,40);assert.equal($('x').value,'20');assert.equal($('y').value,'20');
 $('reset').click();assert.equal($('x').value,'0');assert.equal($('zoom').value,'1');
 pointer('pointerdown',0,0,1);pointer('pointerdown',100,0,2);pointer('pointermove',200,0,2);assert.equal(Number($('zoom').value),2);
 pointer('pointercancel',0,0,1);pointer('pointerup',200,0,2);$('reset').click();
 const menu=doc.querySelector('[data-action="invert"]');menu.closest('details').open=true;menu.click();assert.equal($('invert').checked,true);assert.equal(menu.closest('details').open,false);
 $('frame').click();const inverted=new Uint8Array(await downloads.at(-1).blob.arrayBuffer());
 for(let i=0;i<4000;i++)assert.equal(inverted[i],(~approved[i])&((i%16===15)?0xc0:0xff));
 $('dither').value='bayer';$('dither').dispatchEvent(new window.Event('input'));$('threshold').value=200;$('threshold').dispatchEvent(new window.Event('input'));assert.equal($('threshold-value').textContent,'200');
 const file=new Blob([fs.readFileSync(path.join(ROOT,'web/reference.png'))],{type:'image/png'});Object.defineProperty(file,'name',{value:'local.png'});Object.defineProperty($('file'),'files',{value:[file],configurable:true});$('file').dispatchEvent(new window.Event('change'));
 for(let n=0;n<100&&$('image-name').textContent!=='local.png';n++)await new Promise(r=>setTimeout(r,5));assert.equal($('image-name').textContent,'local.png');
 const details=doc.querySelector('details');details.open=true;doc.dispatchEvent(new window.KeyboardEvent('keydown',{key:'Escape'}));assert.equal(details.open,false);assert.equal(doc.activeElement,details.querySelector('summary'));
 await tick();dom.window.close();
});
